function getRandomInt(max) {
  return Math.floor(Math.random() * max);
}

function createPokemon(pokemon, index) {
    let pokemonFilename = pokemon.name.toLowerCase().replace(/\W/g, '');

    let container = document.createElement("div");
    container.classList = "pokemon-container pokemon";
    container.style.backgroundColor = pokemon.type1.background;
    if(Object.hasOwn(pokemon, "type2")) {
        container.style.borderColor = pokemon.type2.border;
    }
    else {
        container.style.borderColor = pokemon.type1.border;
    }

    let imageAndName = document.createElement("div");
    imageAndName.className = "image-and-name";
    container.appendChild(imageAndName);

    let imageContainer = document.createElement("div");
    imageContainer.className = "image-container";
    imageAndName.appendChild(imageContainer);

    let image = document.createElement("img");
    image.src = "/assets/images/pokemon/" + pokemonFilename + ".png";
    imageContainer.appendChild(image);

    let nameContainer = document.createElement("div");
    nameContainer.className = "name-container";
    imageAndName.appendChild(nameContainer);

    let name = document.createElement("span");
    name.textContent = pokemon.name;
    nameContainer.appendChild(name);

    let rerollAndTypes = document.createElement("div");
    rerollAndTypes.className = "reroll-and-types";
    container.appendChild(rerollAndTypes);

    let reroll = document.createElement("div");
    reroll.className = "reroll";
    rerollAndTypes.appendChild(reroll);

    let rerollButton = document.createElement("input");
    rerollButton.type = "image";
    rerollButton.src = "/assets/images/reroll-pokemon.png";
    rerollButton.addEventListener("click", ()=>{anythingGoes(index)});
    reroll.appendChild(rerollButton);

    let types = document.createElement("div");
    types.className = "types";
    rerollAndTypes.appendChild(types);

    let typesDescriptor = document.createElement("div");
    typesDescriptor.className = "type-descriptor";
    types.appendChild(typesDescriptor);

    let typesContainer = document.createElement("div");
    typesContainer.className = "types-container"
    types.appendChild(typesContainer);

    let type1 = document.createElement("span");
    type1.className = "type";
    type1.textContent = pokemon.type1.name;
    type1.style.backgroundColor = pokemon.type1.color;
    typesContainer.appendChild(type1);

    if(Object.hasOwn(pokemon, "type2")){
        let type2 = document.createElement("span");
        type2.className = "type";
        type2.textContent = pokemon.type2.name;
        type2.style.backgroundColor = pokemon.type2.color;
        typesContainer.appendChild(type2)
        typesDescriptor.textContent = "Types:";
    } else {
        typesDescriptor.textContent = "Type:";
    }

    for (let i = 1; i < 5; i++) {
        let move = document.createElement("div");
        move.className = "move";
        container.appendChild(move);
        
        if(Object.hasOwn(pokemon, "move"+i))
        {
            let moveName = document.createElement("div");
            moveName.textContent = pokemon["move"+i];
            move.appendChild(moveName);

            let type = pokemon["move"+i+"type"];
            let moveType = document.createElement("div");
            moveType.textContent = type.name;
            moveType.style.backgroundColor = type.color;
            move.appendChild(moveType);
        }
    }
    return container;
}

function anythingGoes(index) {
    globalPokemon[index] = ""
    let keys = Object.keys(PokemonsType)
    // remove pokemon we already have
    keys = keys.filter((el) => { return !globalPokemon.includes( el ); });
    let random = getRandomInt(keys.length);
    let pokename = keys[random];
    let pokemon;
    if (Object.hasOwn(AnythingGoesPokemonsType, pokename)){
        pokemon = AnythingGoesPokemonsType[pokename];
    } else {
        pokemon = PokemonsType[[pokename]];
    }
    globalPokemon[index] = pokemon.name;
    let pokemonHTML = createPokemon(pokemon, index);
    let wrapper = document.querySelector(".inner-wrapper");
    wrapper.children[index].replaceWith(pokemonHTML);
}

function init() {
    console.log("init");
    document.querySelector(".pokemon-container:nth-child(1) input").addEventListener("click", ()=>{anythingGoes(0)});
    document.querySelector(".pokemon-container:nth-child(2) input").addEventListener("click", ()=>{anythingGoes(1)});
    document.querySelector(".pokemon-container:nth-child(3) input").addEventListener("click", ()=>{anythingGoes(2)});
    document.querySelector(".pokemon-container:nth-child(4) input").addEventListener("click", ()=>{anythingGoes(3)});
    document.querySelector(".pokemon-container:nth-child(5) input").addEventListener("click", ()=>{anythingGoes(4)});
    document.querySelector(".pokemon-container:nth-child(6) input").addEventListener("click", ()=>{anythingGoes(5)});
}

